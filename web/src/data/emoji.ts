const RECENT_KEY = "kivora.emoji.recent";
const RECENT_MAX = 32;

export function recentEmoji(): string[] {
  try {
    const raw = window.localStorage.getItem(RECENT_KEY);
    return raw ? (JSON.parse(raw) as string[]).slice(0, RECENT_MAX) : [];
  } catch {
    return [];
  }
}

export function rememberEmoji(emoji: string): void {
  try {
    const next = [emoji, ...recentEmoji().filter((e) => e !== emoji)].slice(0, RECENT_MAX);
    window.localStorage.setItem(RECENT_KEY, JSON.stringify(next));
  } catch {
    /* private mode: recents just do not persist */
  }
}

export function searchEmoji(query: string): string[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return [];
  const hits: string[] = [];
  for (const [emoji, words] of Object.entries(KEYWORDS)) {
    if (words.includes(needle)) hits.push(emoji);
  }
  return hits;
}
